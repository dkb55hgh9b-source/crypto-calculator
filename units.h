// Перевод v из единицы from в единицу to внутри категории c. false — если id не найден.
inline bool convert(const Category& c, const std::string& from, const std::string& to,
                    double v, double& out) {
    const Unit* f = nullptr;
    const Unit* t = nullptr;
    for (const Unit& u : c.units) {
        if (from == u.id) f = &u;
        if (to == u.id) t = &u;
    }
    if (!f || !t) return false;

    if (c.temperature) {
        double celsius = v;
        if (from == "°F") celsius = (v - 32.0) * 5.0 / 9.0;
        else if (from == "K") celsius = v - 273.15;
        if (to == "°F") out = celsius * 9.0 / 5.0 + 32.0;
        else if (to == "K") out = celsius + 273.15;
        else out = celsius;
        return true;
    }
    out = v * f->factor / t->factor;
    return true;
}

